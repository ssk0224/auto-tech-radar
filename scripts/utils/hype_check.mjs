// 新しく生成する原稿（note・Web 記事・X）に入れない誇張・結果保証の表現（2026-10-21）。
// 生成スクリプトのプロンプトの禁止指示と、生成後の検査で同じ定義を使う。
// claims_check.mjs（FORBIDDEN）とは別にしている: あちらは公開中の note・既存原稿も CI で検査するため、
// ここに足すと公開済みの記事が一斉に検出される。こちらは新規生成物だけに使う
// [検出する正規表現, プロンプトで禁止を伝える語（null は下の金額の指示で伝える）, 不採用の理由]
export const HYPE_RULES = [
  [/一発(?:で)?(?:起動|稼働|導入|構築|デプロイ)/, "一発起動", "手順どおりに動く保証のない表現"],
  [/コピペで本番/, "コピペで本番", "動作未検証の手順を本番でそのまま使えるかのような表現"],
  [/怪物級|モンスター級/, "怪物級", "根拠のない誇張"],
  [/驚異的|驚異の/, "驚異的", "根拠のない誇張"],
  [/即決/, "即決", "成約を保証するかのような表現"],
  [/爆発的/, "爆発的", "根拠のない誇張"],
  [/稼げ|儲か/, "稼げる", "収益を保証するかのような表現"],
  // 「必ず .env に置く」のような手順の注意書きまで弾くと不採用が増えて Gemini の枠を浪費するため、
  // 結果（収益・受注・成功など）を保証する文脈だけを検出する。「必ず成功するとは限らない」は対象外
  // 「稼働」（動かすこと）は収入の「稼ぐ」ではないので、稼の直後が「働」のときは除く（下の金額の規則も同じ）
  [/必ず[^\n。、]{0,12}?(?:稼(?!働)|儲|受注|成約|売れ|成功|成果|利益|収益|満足|役立|決ま|勝て|採用され|削減でき|向上|回収)(?![^\n。]{0,8}(?:とは限|わけでは|保証))/, "必ず", "結果を保証する表現"],
  // 収入・売上の金額（見込み・目標を含む）。見積表の工数×単価や価格設定（月額◯円）、
  // 提案先の企業規模（「年商10億円以上の企業」「売上高100億円規模」）は対象外
  [/(?:月収|年収|副収入|不労所得|月商|年商|収入|収益(?!化)|売上|売り上げ|MRR|ARR)[^\n。、\d０-９]{0,4}[\d０-９][\d,，.０-９]*\s*(?:[万億千]円|[万億千](?!円)|円)(?!\s*(?:規模|以上の|超の|クラス|の企業|の会社))/, null, "根拠のない収入・売上の金額"],
  [/[\d０-９][\d,，.０-９]*\s*(?:万|億|千)?円[^\n。]{0,6}?(?:稼(?!働)|儲|の(?:副)?収入|の収益|の売上|の利益|を売り上げ)/, null, "根拠のない収入・売上の金額"],
];

// プロンプトに入れる禁止指示（検査と同じ一覧から作る）
export const HYPE_PROMPT_RULE = `- 生成する文面（Web記事・note・X）では、次の誇張・結果保証の表現を使わないこと: ${HYPE_RULES.filter(([, term]) => term).map(([, term]) => `「${term}」`).join("")}。「必ず〜できる」のように成果・受注・収益を保証する書き方をせず、手順の注意は「〜してください」と書くこと。収入・売上・月収・利益などの金額（見込み・目標・事例を含む）は書かないこと。`;

export function findHype(text) {
  if (!text) return [];
  const hits = [];
  for (const [re, , why] of HYPE_RULES) {
    const m = text.match(re);
    if (m) hits.push(`${why} ("${m[0]}")`);
  }
  return hits;
}

// 公開する文面（Web 記事・note の無料部分・X）に書かない、確かめられない評価の語（leakhunt C3、2026-10-22）。
// README と照合できない最上級・絶対の評価や、根拠の無い評判（注目・熱狂など）は、README に同じ主張があっても訳語の誇張になりやすい。
// HYPE_RULES と違い、生成時の検査に加えて掲載中のすべての Web 記事と note の無料部分にも使う（tests/hype_check.test.mjs）
export const UNVERIFIABLE_PRAISE_RULES = [
  [/革新的|革命的|画期的|劇的|飛躍的|極限|究極|最高峰|最強|世界(?:初|最高|最速|一)|史上(?:初|最)|業界(?:初|最|唯一)|唯一無二|完璧|無敵|神ツール|爆速|超高速|超軽量|妥協のない/, "確かめられない最上級・絶対の評価"],
  [/完全(?:に)?(?:排除|除去|防止|防ぐ|防げ|解決|保証|互換|準拠|自動化|再現|無料)|ゼロクラッシュ|(?:ハルシネーション|幻覚)[^\n。]{0,6}(?:ゼロ|0%|完全)/, "確かめられない絶対の保証"],
  [/シリコンバレー|震撼|熱狂|席巻|独走|世界中(?:の|で)[^\n。]{0,12}(?:注目|話題|エンジニア)|注目を集め/, "根拠の無い評判・注目度"],
];
export const UNVERIFIABLE_PRAISE_PROMPT_RULE = "- 「革新的」「劇的」「極限」「最高峰」「完全に排除」「超高速」のような最上級・絶対の評価や、「シリコンバレーで話題」「注目を集めている」のような評判は書かないこと。README に書かれている事実（機能・数値）だけを書くこと。";

export function findUnverifiablePraise(text) {
  if (!text) return [];
  const hits = [];
  for (const [re, why] of UNVERIFIABLE_PRAISE_RULES) {
    const m = String(text).replace(/```[\s\S]*?```/g, "").match(re);
    if (m) hits.push(`${why} ("${m[0]}")`);
  }
  return hits;
}
